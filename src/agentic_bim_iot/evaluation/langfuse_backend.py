from collections.abc import Sequence

from langfuse import Evaluation, get_client

from agentic_bim_iot.evaluation.models import EvaluationCaseResult, EvaluationReport, EvaluationSample, EvaluationScore


class LangfuseEvaluationBackend:
    """Langfuse implementation of the evaluation Layer it executes a benchmark on a dataset
    and calculates metrics like route accuracy, intent accuracy, the expected output and the generated one,
    load the results and generate a report """
    def __init__(self) -> None:
        self._client = get_client()

    @property
    def name(self) -> str:
        return "langfuse"

    def evaluate(self, experiment_name: str, samples: Sequence[EvaluationSample]) -> EvaluationReport:
        data = [
            {
                "input": sample.case.input_query,
                "expected_output": sample.case.expected_output,
                "metadata": {
                    "case_id": sample.case.case_id,
                    "actual_output": sample.actual_output,
                    "expected_route": sample.case.expected_route,
                    "actual_route": sample.actual_route,
                    "expected_intent": sample.case.expected_intent,
                    "actual_intent": sample.actual_intent,
                    "trace_id": sample.trace_id,
                    **sample.case.metadata,
                    **sample.metadata,
                },
            }
            for sample in samples
        ]

        def task(*, item, **kwargs):
            return item["metadata"]["actual_output"]

        def normalized_exact_match(*, input, output, expected_output, metadata, **kwargs):
            """responsible fot normalize the match between the expected output and the generated putput"""
            if expected_output is None:
                return Evaluation(
                    name="normalized_exact_match",
                    value=None,
                    comment="No expected output was configured for this evaluation case.",
                )
            actual = str(output).strip().casefold()
            expected = str(expected_output).strip().casefold()
            score = 1.0 if actual == expected else 0.0
            return Evaluation(name="normalized_exact_match", value=score)

        def route_accuracy(*, input, output, expected_output, metadata, **kwargs):
            """Evaluate the route accuracy generated by the Supervisor"""
            expected_route = metadata.get("expected_route")
            actual_route = metadata.get("actual_route")
            if expected_route is None:
                return Evaluation(
                    name="route_accuracy",
                    value=None,
                    comment="No expected route was configured.",
                )
            score = 1.0 if actual_route == expected_route else 0.0
            return Evaluation(name="route_accuracy",value=score)

        def intent_accuracy(*, input, output, expected_output, metadata, **kwargs):
            """Evaluate the intent accuracy generated by the supervisor"""
            expected_intent = metadata.get("expected_intent")
            actual_intent = metadata.get("actual_intent")
            if expected_intent is None:
                return Evaluation(name="intent_accuracy", value=None, comment="No expected intent was configured.")
            score = 1.0 if actual_intent == expected_intent else 0.0
            return Evaluation(name="intent_accuracy", value=score)

        self._client.run_experiment(
            name=experiment_name,
            data=data,
            task=task,
            evaluators=[
                normalized_exact_match,
                route_accuracy,
                intent_accuracy,
            ],
        )

        self._client.flush()
        return self._build_report(experiment_name=experiment_name, samples=samples)

    def _build_report(self, experiment_name: str, samples: Sequence[EvaluationSample]) -> EvaluationReport:
        """Build the report that has the metrcis used for the evaluation"""
        results = []
        for sample in samples:
            scores = []
            if sample.case.expected_output is not None:
                actual = sample.actual_output.strip().casefold()
                expected = sample.case.expected_output.strip().casefold()
                scores.append(EvaluationScore(metric="normalized_exact_match", score=1.0 if actual == expected else 0.0))
            if sample.case.expected_route is not None:
                scores.append(EvaluationScore(metric="route_accuracy",score=1.0 if sample.actual_route == sample.case.expected_route else 0.0))
            if sample.case.expected_intent is not None:
                scores.append(EvaluationScore(metric="intent_accuracy",score=1.0 if sample.actual_intent == sample.case.expected_intent else 0.0))
            results.append(EvaluationCaseResult(case_id=sample.case.case_id, actual_output=sample.actual_output, scores=tuple(scores)))

        return EvaluationReport(framework=self.name, experiment_name=experiment_name, results=tuple(results))